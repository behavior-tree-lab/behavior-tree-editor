// Regenerates src/app/services/schema.data.js from the canonical
// src/assets/data/nodes.schema.json so the node schema is bundled into the
// Electron build as an Angular value (gulp does not copy src/assets/data).
//
// Usage: node scripts/gen-schema-js.js
/* jshint node: true, strict: false */
'use strict';

var fs = require('fs');
var path = require('path');

var root = path.resolve(__dirname, '..');
var jsonPath = path.join(root, 'src', 'assets', 'data', 'nodes.schema.json');
var outPath = path.join(root, 'src', 'app', 'services', 'schema.data.js');

var data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
var body = JSON.stringify(data, null, 2).split('\n').join('\n    ');

var out =
  '// GENERATED FILE - do not edit by hand.\n' +
  '// Source of truth: src/assets/data/nodes.schema.json (itself generated by\n' +
  '// haibot/cmd/btschema from the Go runtime node definitions).\n' +
  '// Regenerate with: node scripts/gen-schema-js.js\n' +
  '//\n' +
  '// Bundled as an Angular value so the schema is available offline in the\n' +
  '// Electron build without a network/file fetch (gulp does not copy\n' +
  '// src/assets/data into build/).\n' +
  '(function() {\n' +
  "  'use strict';\n\n" +
  '  var schema = ' + body + ';\n' +
  '  if (typeof window !== \'undefined\') {\n' +
  '    window.b3e = window.b3e || {};\n' +
  '    window.b3e.schema = schema;\n' +
  '  }\n\n' +
  '  angular\n' +
  "    .module('app')\n" +
  "    .value('nodesSchemaData', schema);\n" +
  '})();\n';

fs.writeFileSync(outPath, out);
console.log('wrote ' + outPath);
